"""
Extract minimal text embedding code from the installed fastembed into embedder.py,
preserving the sources in fastembed_source/ for audit.

Run: uv run --with fastembed==0.9.0 --with huggingface-hub==1.9.2 --group test python scripts/extract_from_fastembed.py
"""

import importlib.metadata
import inspect
import shutil
import subprocess
import sys
from pathlib import Path

from fastembed.common.preprocessor_utils import (
    _resolve_max_context,
    _valid_context,
    iter_special_tokens,
    load_special_tokens,
    load_tokenizer,
)
from fastembed.common.utils import normalize, iter_batch
from fastembed.common.onnx_model import OnnxModel
from fastembed.text.onnx_text_model import OnnxTextModel
from fastembed.text.onnx_embedding import OnnxTextEmbedding

# --- Verify source version ---
v = importlib.metadata.version("fastembed")
assert v == "0.9.0", f"Expected fastembed 0.9.0, got {v}"


def get_loc(fn):
    """Get short source location string for a function."""
    f = inspect.getfile(fn).split("site-packages/")[-1]
    start = inspect.getsourcelines(fn)[1]
    num_lines = len(inspect.getsource(fn).splitlines())
    return f"{f}:{start}-{start + num_lines - 1}"


# --- Build provenance map ---
provenance = {
    "load_special_tokens": get_loc(load_special_tokens),
    "iter_special_tokens": get_loc(iter_special_tokens),
    "_valid_context": get_loc(_valid_context),
    "_resolve_max_context": get_loc(_resolve_max_context),
    "load_tokenizer": get_loc(load_tokenizer),
    "normalize": get_loc(normalize),
    "iter_batch": get_loc(iter_batch),
    "OnnxModel._load_onnx_model": get_loc(OnnxModel._load_onnx_model),
    "OnnxTextModel.onnx_embed": get_loc(OnnxTextModel.onnx_embed),
    "OnnxTextModel._embed_documents": get_loc(OnnxTextModel._embed_documents),
    "OnnxTextEmbedding._post_process_onnx_output": get_loc(
        OnnxTextEmbedding._post_process_onnx_output
    ),
}

# --- Preserve the source files for audit ---
src_root = Path(__file__).resolve().parent.parent / "fastembed_source"
src_root.mkdir(exist_ok=True)
for fn in (
    load_special_tokens,
    load_tokenizer,
    normalize,
    iter_batch,
    OnnxModel._load_onnx_model,
    OnnxTextModel.onnx_embed,
    OnnxTextModel._embed_documents,
    OnnxTextEmbedding._post_process_onnx_output,
):
    shutil.copy(inspect.getfile(fn), src_root / Path(inspect.getfile(fn)).name)

# --- Extract exact function source code ---
src_load_special_tokens = inspect.getsource(load_special_tokens)
src_iter_special_tokens = inspect.getsource(iter_special_tokens)

# mypy (warn_return_any) rejects `return tokens_map` when tokens_map comes from
# json.load; annotate at the load site. Assert-match: upstream drift fails loudly.
_old = "        tokens_map = json.load(tokens_map_file)"
assert _old in src_load_special_tokens, "upstream body drifted, patch stale"
src_load_special_tokens = src_load_special_tokens.replace(
    _old, "        tokens_map: dict[str, Any] = json.load(tokens_map_file)"
)

src_valid_context = inspect.getsource(_valid_context)
src_resolve_max_context = inspect.getsource(_resolve_max_context)
src_load_tokenizer = inspect.getsource(load_tokenizer)
src_iter_batch = inspect.getsource(iter_batch)
src_load_onnx = inspect.getsource(OnnxModel._load_onnx_model)
src_embed_documents = inspect.getsource(OnnxTextModel._embed_documents)
src_post_process = inspect.getsource(OnnxTextEmbedding._post_process_onnx_output)

# --- Write embedder.py ---
# We inline the function bodies into a single module, noting exactly where
# each block comes from. Changes from the original are marked with CHANGED.

output = Path(__file__).resolve().parent.parent / "embedder.py"

output.write_text(f'''\
"""
Minimal ONNX text embedder adapted from fastembed {v}.

Generated by scripts/extract_from_fastembed.py
"""

import json
import sys
from itertools import islice
from pathlib import Path
from typing import Any, Iterable, Iterator, TypeVar

import numpy as np
import onnxruntime as ort
from tokenizers import AddedToken, Tokenizer

T = TypeVar("T")


{src_load_special_tokens}

{src_iter_special_tokens}

{src_valid_context}

{src_resolve_max_context}

{src_load_tokenizer}


class TextEmbedder:
    """Minimal ONNX text embedder. Extracted from fastembed {v} OnnxTextEmbedding."""

    def __init__(self, model_dir: str | Path):
        model_dir = Path(model_dir)

        # --- From {provenance["load_tokenizer"]} (load_tokenizer) ---
        # CHANGED: called as the extracted function (the original module also imports
        #          fastembed.image, which pulls Pillow); special-token map unused
        self.tokenizer, _ = load_tokenizer(model_dir)

        # --- From {provenance["OnnxModel._load_onnx_model"]} (OnnxModel._load_onnx_model) ---
        # CHANGED: hardcoded CPUExecutionProvider (Lambda is CPU-only); removed
        #          CUDA/provider selection, warnings, thread config, extra_session_options
        so = ort.SessionOptions()
        so.graph_optimization_level = ort.GraphOptimizationLevel.ORT_ENABLE_ALL
        self.model = ort.InferenceSession(
            str(model_dir / "onnx" / "model.onnx"),
            providers=["CPUExecutionProvider"],
            sess_options=so,
        )
        self._input_names = {{node.name for node in self.model.get_inputs()}}

    def embed(
        self, texts: list[str], batch_size: int = 256
    ) -> Iterable[np.ndarray]:
        """Embed texts. Yields one L2-normalized numpy array per text.

        From {provenance["OnnxTextModel._embed_documents"]} (_embed_documents)
        CHANGED: removed parallel processing, removed lazy model loading,
                 removed model_name/cache_dir params (model already loaded in __init__)
        """
        for batch in iter_batch(texts, batch_size):
            # --- From {provenance["OnnxTextModel.onnx_embed"]} (onnx_embed) ---
            # CHANGED: cached input names; removed _preprocess_onnx_input passthrough (no-op
            #          here), OnnxOutputContext wrapper, ONNX_OUTPUT_NAMES, lazy tokenizer loading
            encoded = self.tokenizer.encode_batch(batch)
            input_ids = np.array([e.ids for e in encoded])
            attention_mask = np.array([e.attention_mask for e in encoded])
            onnx_input: dict[str, np.ndarray] = {{
                "input_ids": np.array(input_ids, dtype=np.int64),
            }}
            if "attention_mask" in self._input_names:
                onnx_input["attention_mask"] = np.array(attention_mask, dtype=np.int64)
            if "token_type_ids" in self._input_names:
                onnx_input["token_type_ids"] = np.array(
                    [np.zeros(len(e), dtype=np.int64) for e in input_ids], dtype=np.int64
                )

            model_output = self.model.run(None, onnx_input)[0]

            # --- From {provenance["OnnxTextEmbedding._post_process_onnx_output"]} ---
            # (_post_process_onnx_output) — UNCHANGED
            if model_output.ndim == 3:  # (batch_size, seq_len, embedding_dim)
                model_output = model_output[:, 0]
            elif model_output.ndim == 2:  # (batch_size, embedding_dim)
                pass
            else:
                raise ValueError(f"Unsupported embedding shape: {{model_output.shape}}")

            # --- From {provenance["normalize"]} (normalize) ---
            # CHANGED: inlined, hardcoded p=2 dim=1 (only values ever used)
            norm = np.linalg.norm(model_output, ord=2, axis=1, keepdims=True)
            norm = np.maximum(norm, 1e-12)  # Avoid division by zero
            normalized = model_output / norm

            yield from normalized


{src_iter_batch}
''')

print(f"Wrote {output}")
print(f"Extracted from fastembed {v}")
print(f"Preserved sources in {src_root}")
print()

# The generated file must land pre-formatted, or every regeneration
# re-dirties against the repo's ruff-format hook.
subprocess.run(
    [sys.executable, "-m", "ruff", "format", str(output)],
    check=True,
)
